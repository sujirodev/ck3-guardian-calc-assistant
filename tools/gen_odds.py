# Generates common/script_values/tnt_ga_rank_odds.txt.
# Usage: python tools/gen_odds.py common/script_values/tnt_ga_rank_odds.txt
#
# Odds of reaching each education rank. The n birthdays left are independent
# rolls with chance p, so successes K ~ Binomial(n, p) and the final points
# are shift + 2K, where shift = current points + coming-of-age bonuses at
# their average. Rank R needs more than T points (T = 7, 12, 17 for ranks
# 2, 3, 4), i.e. K >= k* = floor((T - shift) / 2) + 1.
# CK3 script values have no loops, so every term is written out.
import sys
from math import comb

MAX_N = 10  # birthdays from 6 to 15


def pmf(k):
    lines = [f"# P(K = {k}) for n = scope:tnt_ga_n, p = scope:tnt_ga_p.",
             f"tnt_ga_pmf_{k}_value = {{", "\tvalue = 0"]
    for n in range(k, MAX_N + 1):
        ops = [f"\t\tvalue = {comb(n, k)}"]
        ops += ["\t\tmultiply = scope:tnt_ga_p"] * k
        ops += ["\t\tmultiply = scope:tnt_ga_q"] * (n - k)
        lines.append(f"\tif = {{\n\t\tlimit = {{ scope:tnt_ga_n = {n} }}\n" + "\n".join(ops) + "\n\t}")
    lines.append("}")
    return "\n".join(lines)


def odds(rank, threshold):
    adds = "\n".join(
        f"\tif = {{ limit = {{ scope:tnt_ga_kstar <= {k} scope:tnt_ga_n >= {k} }} add = tnt_ga_pmf_{k}_value }}"
        for k in range(MAX_N + 1))
    return f"""# Percent chance of ending at rank {rank} or better (more than {threshold} points).
tnt_ga_odds_rank_{rank}_core_value = {{
	value = tnt_ga_chance_core_value
	divide = 100
	save_temporary_value_as = tnt_ga_p
	value = 1
	subtract = scope:tnt_ga_p
	save_temporary_value_as = tnt_ga_q
	value = tnt_ga_rolls_left_core_value
	save_temporary_value_as = tnt_ga_n
	value = tnt_ga_projected_points_core_value
	subtract = {{ value = scope:tnt_ga_p multiply = scope:tnt_ga_n multiply = 2 }}
	save_temporary_value_as = tnt_ga_shift
	value = {threshold}
	subtract = scope:tnt_ga_shift
	divide = 2
	floor = yes
	add = 1
	save_temporary_value_as = tnt_ga_kstar
	value = 0
{adds}
	multiply = 100
	max = 100
}}

tnt_ga_odds_rank_{rank}_value = {{
	value = 0
	if = {{
		limit = {{ tnt_ga_root_is_guardian_trigger_value > 0 }}
		save_temporary_scope_as = tnt_ga_guardian
		scope:tnt_ga_other = {{ save_temporary_scope_as = tnt_ga_ward }}
		value = tnt_ga_odds_rank_{rank}_core_value
	}}
	else_if = {{
		limit = {{ tnt_ga_root_is_ward_trigger_value > 0 }}
		save_temporary_scope_as = tnt_ga_ward
		scope:tnt_ga_other = {{ save_temporary_scope_as = tnt_ga_guardian }}
		value = tnt_ga_odds_rank_{rank}_core_value
	}}
}}"""


out = ["﻿" + "#" * 72,
       "# Guardian Calculation Assistant: odds per education rank (generated by",
       "# tools/gen_odds.py; do not edit by hand).",
       "#" * 72, ""]
out += [pmf(k) + "\n" for k in range(MAX_N + 1)]
out += [odds(r, t) + "\n" for r, t in [(2, "education_level_1"), (3, "education_level_2"), (4, "education_level_3")]]
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(sys.argv[1])
